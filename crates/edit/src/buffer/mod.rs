/// In order to group actions into a single undo step,
/// we need to know the type of action that was performed.
/// This stores the action type.
#[derive(Copy, Clone, Eq, PartialEq)]
enum HistoryType {
    Other,
    Write,
    Delete,
}

/// An undo/redo entry.
struct HistoryEntry {
    /// [`TextBuffer::cursor`] position before the change was made.
    cursor_before: Point,
    /// [`TextBuffer::selection`] before the change was made.
    selection_before: Option<TextBufferSelection>,
    /// [`TextBuffer::stats`] before the change was made.
    stats_before: TextBufferStatistics,
    /// [`GapBuffer::generation`] before the change was made.
    ///
    /// **NOTE:** Entries with the same generation are grouped together.
    generation_before: u32,
    /// Logical cursor position where the change took place.
    /// The position is at the start of the changed range.
    cursor: Point,
    /// Text that was deleted from the buffer.
    deleted: Vec<u8>,
    /// Text that was added to the buffer.
    added: Vec<u8>,

    /// Content digest + byte length of the whole document either side of
    /// this entry's edit, recorded as the edit happened. Ground truth for
    /// the undo/redo content checks: undoing this entry has to land on
    /// `before`, redoing it on `after`. Unlike `deleted`/`added` these are
    /// *not* swapped when the entry changes stacks -- "before the edit" and
    /// "after the edit" mean the same thing in both directions.
    #[cfg(feature = "sanity")]
    content_before: ContentDigest,
    #[cfg(feature = "sanity")]
    content_after: ContentDigest,
}

/// See [`HistoryEntry::content_before`]. The length rides along because a
/// bare hash mismatch says nothing about *how* the content diverged.
#[cfg(feature = "sanity")]
#[derive(Copy, Clone, Default, Eq, PartialEq)]
pub(super) struct ContentDigest {
    hash: u64,
    len: usize,
}

#[cfg(feature = "sanity")]
impl fmt::Display for ContentDigest {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{:016x}/{}b", self.hash, self.len)
    }
}

